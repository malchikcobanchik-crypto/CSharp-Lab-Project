
namespace CSharpLab
{
    public static class MathUtils
    {
        /// <summary>
        /// Складывает два целых числа.
        /// </summary>
        /// <param name="a">Первое число.</param>
        /// <param name="b">Второе число.</param>
        /// <returns>Сумма чисел a и b.</returns>
        public static int Add(int a, int b)
        {
            return a + b;
        }
    }
}
